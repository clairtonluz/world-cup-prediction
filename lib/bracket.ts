const officialThirdPlaceAssignments = new Map(
  OFFICIAL_THIRD_PLACE_MATRIX.split("\n").map((line) => {
    const [groups, assignment] = line.split(":");
    return [groups, assignment];
  }),
);

export function calculateAllGroupStandings(matches: BracketMatch[]) {
  return new Map(
    GROUP_CODES.map((groupCode) => [
      groupCode,
      calculateGroupStandings(matches.filter((match) => match.groupCode === groupCode)),
    ]),
  );
}

export function selectBestThirdPlaced(
  groupStandings: Map<GroupCodeValue, StandingRow[]>,
) {
  return GROUP_CODES.flatMap((groupCode) => {
    const standing = groupStandings.get(groupCode)?.[2];
    return standing ? [{ groupCode, standing }] : [];
  })
    .sort(
      (a, b) =>
        compareStandingRows(a.standing, b.standing) ||
        a.groupCode.localeCompare(b.groupCode),
    )
    .slice(0, 8);
}

export function resolveBracketParticipants(matches: BracketMatch[]) {
  const standings = calculateAllGroupStandings(matches);
  const selectedThirds = selectBestThirdPlaced(standings);
  const thirdKey = selectedThirds
    .map(({ groupCode }) => groupCode)
    .sort()
    .join("");
  const thirdAssignment = officialThirdPlaceAssignments.get(thirdKey) ?? null;
  const byNumber = new Map(matches.map((match) => [match.matchNumber, match]));
  const groupStageComplete = matches
    .filter((match) => match.stage === "GROUP_STAGE")
    .every((match) => match.status === "FINISHED");
  const resolutions = new Map<number, ParticipantResolution>();

  for (const match of matches) {
    if (match.stage === "GROUP_STAGE") {
      continue;
    }

    let teamA: string | null = null;
    let teamB: string | null = null;
    let participantsConfirmed = false;

    if (match.stage === "ROUND_OF_32") {
      teamA = resolveGroupSlot(match.teamASlot, match.teamBSlot, standings, thirdAssignment);
      teamB = resolveGroupSlot(match.teamBSlot, match.teamASlot, standings, thirdAssignment);
      participantsConfirmed = groupStageComplete && teamA !== null && teamB !== null;
    } else {
      const sideA = resolveKnockoutSlot(match.teamASlot, byNumber);
      const sideB = resolveKnockoutSlot(match.teamBSlot, byNumber);
      teamA = sideA.team;
      teamB = sideB.team;
      participantsConfirmed =
        sideA.confirmed && sideB.confirmed && teamA !== null && teamB !== null;
    }

    resolutions.set(match.matchNumber, {
      teamA,
      teamB,
      participantsConfirmed,
      projected: !participantsConfirmed && (teamA !== null || teamB !== null),
    });
  }

  return resolutions;
}

function resolveGroupSlot(
  slot: string | null,
  opposingSlot: string | null,
  standings: Map<GroupCodeValue, StandingRow[]>,
  thirdAssignment: string | null,
) {
  if (!slot) {
    return null;
  }

  const fixedPosition = slot.match(/^([12])([A-L])$/);
  if (fixedPosition) {
    const position = Number(fixedPosition[1]) - 1;
    return standings.get(fixedPosition[2] as GroupCodeValue)?.[position]?.team ?? null;
  }

  if (!slot.startsWith("3") || !thirdAssignment || !opposingSlot) {
    return null;
  }

  const assignmentIndex = THIRD_PLACE_WINNER_ORDER.indexOf(
    opposingSlot as (typeof THIRD_PLACE_WINNER_ORDER)[number],
  );
  if (assignmentIndex < 0) {
    return null;
  }

  const groupCode = thirdAssignment[assignmentIndex] as GroupCodeValue | undefined;
  return groupCode ? standings.get(groupCode)?.[2]?.team ?? null : null;
}

function resolveKnockoutSlot(
  slot: string | null,
  matches: Map<number, BracketMatch>,
): { team: string | null; confirmed: boolean } {
  const source = slot?.match(/^(W|RU)(\d+)$/);
  if (!source) {
    return { team: null, confirmed: false };
  }

  const match = matches.get(Number(source[2]));
  if (!match || !match.teamA || !match.teamB) {
    return { team: null, confirmed: false };
  }

  const team = source[1] === "W" ? winningTeam(match) : losingTeam(match);
  return { team, confirmed: match.status === "FINISHED" && team !== null };
}

function winningTeam(match: BracketMatch) {
  if (match.status === "FINISHED" && match.advancingTeam) {
    return match.advancingTeam;
  }

  if (match.teamAScore === null || match.teamBScore === null) {
    return null;
  }

  if (match.teamAScore === match.teamBScore) {
    return null;
  }

  return match.teamAScore > match.teamBScore ? match.teamA : match.teamB;
}

function losingTeam(match: BracketMatch) {
  const winner = winningTeam(match);
  if (!winner) {
    return null;
  }

  return winner === match.teamA ? match.teamB : match.teamA;
}
